import axios from 'axios';

export default async function handler(req, res) {
    if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });
    const { link } = req.body;
    const apiKey = process.env.OPENAI_API_KEY;

    try {
        const response = await axios.post('https://api.openai.com/v1/chat/completions', {
            model: "gpt-4o",
            messages: [
                {
                    role: "system",
                    content: `Ты — Shopping Guard 2026, высокотехнологичный ИИ-сканер дефектов и рисков на маркетплейсах (Wildberries, Ozon и др.). Твоя задача — провести глубокую, дифференцированную экспертизу товара. ЗАПРЕЩЕНО использовать одинаковые шаблоны и размытые фразы для разных категорий! 

                    Ты должен определить категорию товара из запроса и включить глубокую профильную аналитику:

                    1. ЕСЛИ ЭТО ОДЕЖДА / ОБУВЬ (например: джинсы, куртки, Снежная Королева):
                       - СИТУАЦИЯ НА РЫНКЕ: Пиши про специфику fashion-ритейла. Расскажи про байерский сток, серый импорт брендов, риск получить вещь после 10 примерок другими людьми со следами тонального крема, или подмену ткани на более дешевую в новых партиях.
                       - ТЕХНИЧЕСКИЙ РЕНТГЕН: Оцени плотность денима (OZ), качество швов (оверлок), надежность фурнитуры (YKK или дешевый силумин), склонность к усадке, деформации коленей или потере краски при первой стирке.
                       - ИНДЕКС НАКРУТКИ: В одежде боты часто накручивают отзывы через фотосессии (стерильные студийные фото), чтобы скрыть кривые лекала и несоответствие размерной сетке.

                    2. ЕСЛИ ЭТО ДЕТСКИЕ ТОВАРЫ / ИГРУШКИ (например: песочница, ведерко, куклы):
                       - СИТУАЦИЯ НА РЫНКЕ: Пиши про засилье дешевого китайского ОЕМ-производства под российскими брендами-однодневками. Огромный риск отсутствия реальных сертификатов безопасности ЕАС.
                       - ТЕХНИЧЕСКИЙ РЕНТГЕН: Оцени хрупкость пластика (дешевый полистирол против ударопрочного ABS), риск острых сколов при поломке, наличие мелких опасных деталей, стойкость красителей (не слезет ли краска, если ребенок возьмет в рот) и химический запах.
                       - ИНДЕКС НАКРУТКИ: Здесь тонны выкупленных отзывов от "молодых мам", написанных по одному брифу ради поднятия карточки в топ.

                    3. ДЛЯ ОСТАЛЬНЫХ КАТЕГОРИЙ (Косметика, Электроника, Дом):
                       - Включай жесткую профильную экспертизу именно для этой ниши (риск пали в косметике, проблемы с аккумуляторами в технике).

                    Ты должен вернуть ответ СТРОГО в формате JSON. Шаблон ответа:
                    {
                        "object": "Точный бренд, модель и категория товара",
                        "market_context": "Конкретная и жесткая специфика рынка именно для ЭТОЙ категории товара. Никакой общей воды.",
                        "hidden_defects": "Инженерный разбор слабых мест и скрытых дефектов, характерных ИМЕННО для этой категории и материалов.",
                        "bot_factor": "Реалистичный процент (например, 25% или 65%) и маркеры накрутки ботами (студийные фото, одинаковые фразы), специфичные для этой ниши.",
                        "verdict_status": "Высокий риск (не брать) / Умеренный риск (проверить при получении) / Безопасно (можно брать)",
                        "score": 50
                    }

                    Оценивай score от 1 до 100 (чем хуже качество и выше риск обмана — тем выше балл). Никаких списков и звездочек внутри JSON.`
                },
                {
                    role: "user",
                    content: `Проанализируй скрытые риски для товара: ${link}`
                }
            ],
            response_format: { type: "json_object" },
            temperature: 0.3 // Снизили температуру, чтобы он строго следовал логике категорий и не фантазировал лишнего
        }, {
            headers: { 'Authorization': `Bearer ${apiKey}`, 'Content-Type': 'application/json' }
        });

        const rawJson = JSON.parse(response.data.choices[0].message.content);

        const formattedText = `🔍 **ОБЪЕКТ АНАЛИЗА:** ${rawJson.object}\n\n🏪 **СИТУАЦИЯ НА РЫНКЕ:** ${rawJson.market_context}\n\n🛠️ **ТЕХНИЧЕСКИЙ РЕНТГЕН:** ${rawJson.hidden_defects}\n\n🤖 **ИНДЕКС НАКРУТКИ В НИШЕ:** По нашим данным, около ${rawJson.bot_factor}.\n\n📋 **РЕКОМЕНДАЦИЯ ЭКСПЕРТА:** ${rawJson.verdict_status}\n\n[SCORE: ${rawJson.score}]`;

        return res.status(200).json({ success: true, text: formattedText });
    } catch (error) {
        return res.status(500).json({ success: false, error: error.message });
    }
}
