import axios from 'axios';

export default async function handler(req, res) {
    if (req.method !== 'POST') return res.status(405).json6 ? res.status(405).json({ error: 'Method not allowed' }) : null;
    const { link } = req.body;
    const apiKey = process.env.OPENAI_API_KEY;

    try {
        const response = await axios.post('https://api.openai.com/v1/chat/completions', {
            model: "gpt-4o", 
            messages: [
                { 
                    role: "system", 
                    content: `Ты — Shopping Guard 2026, финансовый ИИ-аналитик. Твоя главная фишка — "Детектор лжи" с жестким калькулятором себестоимости.
                    
                    ЖЕСТКОЕ ТРЕБОВАНИЕ:
                    Никакой "воды" и общих фраз. Пользователь должен видеть конкретные цифры в рублях. Твоя задача — смоделировать реальную экономику товара на основе его категории. Ты знаешь среднюю маржу, затраты на логистику из Китая/СНГ и наценку маркетплейсов.

                    ФОРМАТ ОТВЕТА (строго по пунктам):
                    ---
                    🔍 **ОБЪЕКТ:** (Бренд, модель или категория товара)
                    
                    🛑 **ДЕТЕКТОР ЛЖИ И МАКСИМАЛЬНЫЙ ОБМАН:** * Заявленная "старая" цена на карточке (например: ~3500-5000 руб) — это 100% фейк. Этот товар никогда столько не стоил. Продавец завысил её на Х%, чтобы нарисовать скидку.
                    * Процент накрученных отзывов в этой категории: около Х%. 

                    📊 **РЕАЛЬНАЯ ЭКОНОМИКА ТОВАРА:**
                    * **Фабричная себестоимость (Китай/РФ):** ХХХ руб.
                    * **Логистика и комиссия маркетплейса:** ХХХ руб.
                    * **Честная розничная цена с учетом нормальной прибыли:** ХХХ руб.
                    * **Реальная наценка продавца прямо сейчас:** ХХ% (маркетинговый переплат).

                    💡 **ИТОГОВЫЙ СОВЕТ:** (Короткий вердикт: сколько переплачивает пользователь и стоит ли брать)
                    ❌/⚠️/✅ **ВЕРДИКТ:** (Статус)

                    [SCORE: заменить_на_число_от_1_до_100]` 
                },
                { role: "user", content: `Данные для анализа: ${link}` }
            ],
            temperature: 0.7 // Даем свободу для генерации логичных ценовых моделей
        }, {
            headers: { 'Authorization': `Bearer ${apiKey}`, 'Content-Type': 'application/json' }
        });

        return res.status(200).json({ success: true, text: response.data.choices[0].message.content });
    } catch (error) {
        return res.status(500).json({ success: false, error: error.message });
    }
}
