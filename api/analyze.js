import axios from 'axios';

export default async function handler(req, res) {
    if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });
    const { link, priceNow, priceOld } = req.body;
    const apiKey = process.env.OPENAI_API_KEY;

    // Считаем скидку для контекста ИИ
    let discountInfo = "Цены не указаны пользователем, сделай общий экспертный расчет для этой категории.";
    if (priceNow && priceOld) {
        const discount = Math.round(((Number(priceOld) - Number(priceNow)) / Number(priceOld)) * 100);
        discountInfo = `Покупатель видит: Цена сейчас ${priceNow} руб, Зачеркнутая цена ${priceOld} руб. Реальная скидка на экране: ${discount}%.`;
    }

    try {
        const response = await axios.post('https://api.openai.com/v1/chat/completions', {
            model: "gpt-4o", 
            messages: [
                { 
                    role: "system", 
                    content: `Ты — Shopping Guard 2026, циничный и опытный финансовый аналитик маркетплейсов. Ты общаешься с пользователем как с умным взрослым человеком, без банальных лекций и капитанства.

                    КРИТИЧЕСКИЕ ПРАВИЛА:
                    1. Начинай ответ строго с "🔍 **ОБЪЕКТ:**". Никаких вступлений.
                    2. Ты ОБЯЗАН выдать ВСЕ 5 РАЗДЕЛОВ, которые указаны ниже. Тебе запрещено сокращать ответ или выкидывать пункты.
                    3. Никаких списков, дефисов и звездочек в тексте — только сплошные абзацы под каждым заголовком.

                    ОБЯЗАТЕЛЬНАЯ СТРУКТУРА ОТВЕТА:`
                },
                { 
                    role: "user", 
                    content: `Проанализируй товар. Входные данные: ${link}. ${discountInfo}
                    
                    Выдай строго в таком формате:
                    
                    🔍 **ОБЪЕКТ:** (Напиши бренд и модель товара)
                    
                    🛑 **ДЕТЕКТОР ЛЖИ:** (Оцени адекватность цен, если они переданы. Если скидка огромная — разнеси фейковый оверпрайс фактами без банальных объяснений вроде "это трюк для привлечения". Напиши конкретный процент накрутки отзывов ботами в этой категории и как смотреть реальные отзывы)
                    
                    🛠️ **МАТЕРИАЛЫ И КАЧЕСТВО:** (Трезво оцени надежность, пластик/дерево, сборку и скрытые дефекты, с которыми столкнется покупатель)
                    
                    📊 **РЕАЛЬНАЯ ЭКОНОМИКА:** (Смоделируй в рублях: фабричная себестоимость, логистика с комиссией маркетплейса, честная розничная цена с нормальной прибылью. Укажи процент чистой маркетинговой переплаты)
                    
                    💡 **ИТОГОВЫЙ СОВЕТ:** (Жесткий и короткий вердикт: брать, искать замену или продавец зажрался)
                    
                    ❌/⚠️/✅ **ВЕРДИКТ:** (Выбери один статус)

                    [SCORE: число_от_1_до_100]`
                }
            ],
            temperature: 0.6
        }, {
            headers: { 'Authorization': `Bearer ${apiKey}`, 'Content-Type': 'application/json' }
        });

        return res.status(200).json({ success: true, text: response.data.choices[0].message.content });
    } catch (error) {
        return res.status(500).json({ success: false, error: error.message });
    }
}
